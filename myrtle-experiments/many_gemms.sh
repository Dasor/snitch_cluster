runAndExtract(){
    ss="$1"
    echo -e "\tmany_gemms.sh: RUN + EXPORT step"
    uniquePointRegex='^(([0-9]*)x([0-9]*)x([0-9]*))w([0-9]*)-([0-9]*)-([0-9]*)'
