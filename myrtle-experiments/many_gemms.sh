    then
        echo -e "\tmany_gemms.sh: Error: $ss csv file does not exist. Errno $exists"
        return 1
    fi

    if [[ "$2" == "compile" ]]; 
    then
        compile $ss
    fi

    if [[ "$2" == "check" ]]; 
    then
        check $ss
    fi
    
    if [[ "$3" == "run" ]]; 
    then
        runAndExtract $ss
    fi

    if [[ "$4" == "extract" ]]; 
    then
        onlyExtract $ss
    fi

    if [[ "$5" == "clear" ]]; 
    then
        clear $ss
    fi

    if [[ "$5" == "clearLogs" ]]; 
    then
        clearLogs $ss
    fi
    

    echo -e "\tmany_gemms.sh: DONE"
    return 0
}

