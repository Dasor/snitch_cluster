            do
            eatNum='^([0-9])([0-9])*'
            M=$(echo $ts | grep -oE $eatNum)
            tail=${ts#*x}
            N=$(echo $tail | grep -oE $eatNum)
            tail=${tail#*x}
            K=$(echo $tail | grep -oE $eatNum)
